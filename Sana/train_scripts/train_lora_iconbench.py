def log_validation(
    pipeline,
    args,
    accelerator,
    pipeline_args,
    epoch,
    is_final_validation=False,
):
    logger.info(
        f"Running validation... \n Generating {args.num_validation_images} images with prompt:"
        f" {args.validation_prompt}."
    )
    pipeline.text_encoder = pipeline.text_encoder.to(torch.bfloat16)
    pipeline = pipeline.to(accelerator.device)
    pipeline.set_progress_bar_config(disable=True)

    # run inference
    generator = torch.Generator(device=accelerator.device).manual_seed(args.seed) if args.seed else None

    # Add required parameters for pipeline call
    full_pipeline_args = {
        **pipeline_args,
        "height": args.resolution,
        "width": args.resolution,
        "num_inference_steps": 20,  # Default inference steps
        "guidance_scale": 4.5,  # Default guidance scale
        "num_images_per_prompt": 1,
        "use_resolution_binning": False,  # Disable resolution binning to avoid potential issues
    }

    images = []
    for i in range(args.num_validation_images):
        try:
            with torch.no_grad():
                result = pipeline(**full_pipeline_args, generator=generator)
            
            # Handle different return formats from diffusers SanaPipeline
            # The pipeline may return:
            # 1. A list of PIL Images (from diffusers format)
            # 2. A list of tensors (from custom pipeline)
            # 3. An object with .images attribute
            
            if hasattr(result, 'images'):
                # Diffusers format: result.images is a list
                result_images = result.images
            elif isinstance(result, list):
                # Direct list of images/tensors
                result_images = result
            else:
                # Single image/tensor
                result_images = [result]
            
            # Convert to PIL Image if needed
            if len(result_images) > 0:
                img = result_images[0]
                
                # Convert tensor to PIL Image if needed
                if isinstance(img, torch.Tensor):
                    # Normalize from [-1, 1] to [0, 255]
                    img = img.clamp(-1, 1)
                    img = (img + 1) / 2.0  # Scale to [0, 1]
                    img = img.mul(255).add_(0.5).clamp_(0, 255)
                    
                    # Handle different tensor shapes
                    if img.dim() == 4:  # [B, C, H, W]
                        img = img[0]
                    if img.dim() == 3:  # [C, H, W]
                        img = img.permute(1, 2, 0)  # [H, W, C]
                    
                    img = img.to("cpu", torch.uint8).numpy()
                    img = Image.fromarray(img.astype(np.uint8))
                elif not isinstance(img, Image.Image):
                    # Try to convert to PIL Image
                    img = Image.fromarray(np.array(img))
                
                images.append(img)
            else:
                raise ValueError("Pipeline returned empty result")
                
        except Exception as e:
            logger.error(f"Error during validation image generation (attempt {i+1}/{args.num_validation_images}): {e}")
            import traceback
            logger.error(traceback.format_exc())
            # Create a dummy image if generation fails
            dummy_image = Image.new('RGB', (args.resolution, args.resolution), color='black')
            images.append(dummy_image)

    for tracker in accelerator.trackers:
        phase_name = "test" if is_final_validation else "validation"
        if tracker.name == "tensorboard":
            np_images = np.stack([np.asarray(img) for img in images])
            tracker.writer.add_images(phase_name, np_images, epoch, dataformats="NHWC")
        if tracker.name == "wandb":
            tracker.log(
                {
                    phase_name: [
                        wandb.Image(image, caption=f"{i}: {args.validation_prompt}") for i, image in enumerate(images)
                    ]
                }
            )

    del pipeline
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    return images


